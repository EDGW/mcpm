//! Opaque command contract served by `mcpm-exec`, and the error shape it crosses the wire.
//!
//! A handler decodes its own JSON input, emits JSON events and returns an ordinary error.
//! Until handlers become host operations, this module adapts them to the executor: input and
//! events stay untyped JSON, and the operation error is an error report, never a business codec.

use std::{future::Future, marker::PhantomData};

use anyhow::{Result, anyhow};
use serde::{Serialize, Serializer};
use serde_json::Value;
use thiserror::Error;

use mcpm_exec::{Context, DispatchError, Emitter, Operation, Placement, Wire};

use crate::diagnostics::{ErrorReport, RemoteError};

pub(crate) trait Command: Send + Sync + 'static {
    /// Stable identifier; invocation GUIDs are generated by the caller.
    const ID: &'static str;
    fn run(contents: Value, output: &Output) -> Result<()>;
}

/// Event sink of one served call; blocking, because handlers run on the blocking pool.
pub(crate) struct Output {
    emitter: Emitter<Value>,
}

impl Output {
    fn new(emitter: Emitter<Value>) -> Self {
        Self { emitter }
    }

    pub(crate) fn checkpoint(&self) -> Result<()> {
        self.emitter.checkpoint().map_err(|_| Cancelled.into())
    }

    pub(crate) fn send(&self, contents: impl Serialize) -> Result<()> {
        self.checkpoint()?;
        let contents = serde_json::to_value(contents)?;
        self.emitter.emit(contents).map_err(|_| Cancelled.into())
    }
}

impl std::fmt::Debug for Output {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.debug_struct("Output").finish_non_exhaustive()
    }
}

/// Serves one legacy command as a host operation until the command becomes one itself.
#[derive(Debug)]
pub(crate) struct Handler<C>(PhantomData<C>);

impl<C: Command> Operation for Handler<C> {
    const ID: &'static str = C::ID;
    const PLACEMENT: Placement = Placement::Host;
    // Handlers stay in JSON, so every direction is a passthrough except the error report.
    const WIRE: Option<Wire<Self>> = Some(Wire::new(
        passthrough,
        passthrough,
        passthrough,
        passthrough,
        output,
        decode_output,
        encode_error,
        decode_error,
    ));
    type Env = ();
    type Input = Value;
    type Event = Value;
    type Output = ();
    type Error = LegacyError;

    fn run(
        input: Value,
        cx: Context<'_, Self>,
    ) -> impl Future<Output = std::result::Result<(), LegacyError>> + Send {
        let emitter = cx.emitter();
        async move {
            cx.blocking(move || C::run(input, &Output::new(emitter)))
                .await
                .map_err(LegacyError)
        }
    }
}

fn passthrough(value: Value) -> std::result::Result<Value, DispatchError> {
    Ok(value)
}

fn output(_output: ()) -> std::result::Result<Value, DispatchError> {
    Ok(Value::Null)
}

fn decode_output(_value: Value) -> std::result::Result<(), DispatchError> {
    Ok(())
}

fn encode_error(error: LegacyError) -> std::result::Result<Value, DispatchError> {
    serde_json::to_value(error).map_err(|error| DispatchError::Protocol {
        message: error.to_string(),
    })
}

fn decode_error(value: Value) -> std::result::Result<LegacyError, DispatchError> {
    Ok(LegacyError(LegacyError::decode(value)))
}

/// Operation error as the frontend sees it: an error report rebuilt into an error chain.
#[derive(Debug, Error)]
#[error("{0}")]
pub(crate) struct LegacyError(anyhow::Error);

impl Serialize for LegacyError {
    fn serialize<S: Serializer>(&self, serializer: S) -> std::result::Result<S::Ok, S::Error> {
        ErrorReport::capture(&self.0).serialize(serializer)
    }
}

impl LegacyError {
    /// Rebuilds the recorded chain and keeps the remote origin visible to the display layer.
    pub(crate) fn decode(encoded: Value) -> anyhow::Error {
        match serde_json::from_value::<ErrorReport>(encoded) {
            Ok(report) => RemoteError::wrap(report.into_error()),
            Err(error) => RemoteError::wrap(anyhow!("invalid remote error report: {error}")),
        }
    }
}

/// Converts a session failure that carries an undecoded operation error into the frontend model.
pub(crate) fn failure(failure: mcpm_exec::CallFailure) -> anyhow::Error {
    match failure {
        mcpm_exec::CallFailure::Operation(encoded) => LegacyError::decode(encoded),
        mcpm_exec::CallFailure::Dispatch(error) => RemoteError::wrap(error.into()),
        mcpm_exec::CallFailure::Transport(error) => error.into(),
        mcpm_exec::CallFailure::Cancelled => {
            RemoteError::wrap(anyhow!("remote command was cancelled"))
        }
    }
}

/// The call was cancelled before the handler finished.
#[derive(Debug, Error)]
#[error("remote command was cancelled")]
pub(crate) struct Cancelled;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn error_reports_survive_the_wire_with_their_chain() {
        let error = anyhow::anyhow!("inner").context("middle").context("outer");
        let encoded = serde_json::to_value(LegacyError(error)).unwrap();
        let rebuilt = LegacyError::decode(encoded);
        assert!(kako_mc_lib::error::contains::<RemoteError>(rebuilt.as_ref()));
        let report = ErrorReport::capture_with(rebuilt.as_ref(), |cause| {
            (!cause.is::<RemoteError>()).then(|| cause.to_string())
        });
        assert_eq!(report.message, "outer");
        assert_eq!(report.causes, ["middle", "inner"]);
    }
}
